export type SchoolUiLanguage = 'fr' | 'ar';

/** Langue de l'interface : l'arabe seulement pour un établissement configuré en Arabe. */
export function schoolUiLanguage(locale: SchoolLocale): SchoolUiLanguage {
  return locale === 'AR' ? 'ar' : 'fr';
}

/** Champs et contenus arabes : affichés pour Arabe et Bilingue, jamais pour Français. */
export function schoolShowsArabic(locale: SchoolLocale): boolean {
  return locale !== 'FR';
}

/**
 * Libellé texte d'un élément (listes, menus, exports) : français seul en Français, arabe prioritaire
 * en Arabe, les deux en Bilingue (« CP1 / السنة الأولى »). Sans libellé arabe, le français.
 */
export function schoolDisplayName(
  locale: SchoolLocale,
  item: { name: string; nameAr?: string | null },
): string {
  if (!item.nameAr || locale === 'FR') return item.name;
  return locale === 'AR' ? item.nameAr : `${item.name} / ${item.nameAr}`;
}

