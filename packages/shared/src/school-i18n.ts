/** Message d'une anomalie d'import : en arabe d'après son code et son champ, sinon celui du serveur. */
export function schoolImportIssueMessage(
  language: SchoolUiLanguage,
  issue: { code?: string; field?: SchoolImportField; message: string },
): string {
  const arabic = language === 'ar' && issue.code ? SCHOOL_IMPORT_ISSUES_AR[issue.code] : undefined;
  if (!arabic) return issue.message;
  return issue.field ? `${LABELS_AR.importField[issue.field]}: ${arabic}` : arabic;
}

