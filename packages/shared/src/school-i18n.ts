/** Texte de l'interface, avec remplacement des variables `{nom}`. */
export function schoolText(
  language: SchoolUiLanguage,
  key: SchoolTextKey,
  vars: SchoolTextVars = {},
): string {
  const entry = (language === 'ar' ? SCHOOL_TEXT_AR : SCHOOL_TEXT_FR)[key] as Entry | undefined;
  // Clé construite à partir d'une donnée (type d'événement, par exemple) et inconnue ici.
  if (entry === undefined) return key;
  if (typeof entry === 'function') return entry(vars);
  return entry.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

